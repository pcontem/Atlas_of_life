#!/usr/bin/env python3
"""Regenerate docs/QUEUE.md: the ordered work list of clade entries still to be written.

Done = an entry file exists in entries/*/clades/<id>.yaml. Order = depth-first walk of
data/tree/backbone.json (parents before children), except that the subtrees listed in
docs/queue_priority.txt (one node id per line, '#' = comment) come first, in that order.
Run it after every batch:  python3 scripts/queue.py
"""
import json, glob, os, re, collections, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = json.load(open(f"{ROOT}/data/tree/backbone.json"))
by = {r[0]: r for r in rows}
kids = collections.defaultdict(list)
for r in rows:
    kids[r[2]].append(r)
done = {os.path.basename(f)[:-5] for f in glob.glob(f"{ROOT}/entries/*/clades/*.yaml")}

def tips(i):
    return sum(1 if c[5] == "g" else tips(c[0]) for c in kids[i])

prio = []
p = f"{ROOT}/docs/queue_priority.txt"
if os.path.exists(p):
    prio = [l.split("#")[0].strip() for l in open(p) if l.split("#")[0].strip()]
    bad = [x for x in prio if x not in by]
    if bad:
        sys.exit(f"queue_priority.txt: unknown node ids: {bad}")

order, seen = [], set()
def walk(i, depth):
    if i in seen:
        return
    seen.add(i)
    r = by[i]
    if r[5] == "c":
        order.append((r, depth))
        for c in kids[i]:
            walk(c[0], depth + 1)
for i in prio:
    walk(i, 0)
walk("vida", 0)

total = len(order)
n_done = sum(1 for r, _ in order if r[0] in done)
todo = [(r, d) for r, d in order if r[0] not in done]
# clades whose entry exists in a volume (not in backbone) are not counted here
out = []
w = out.append
w("# Clade work queue\n")
w("Generated by `python3 scripts/queue.py` — **do not edit by hand**. Change the order in "
  "[`queue_priority.txt`](queue_priority.txt) and re-run the script.\n")
w("## How Claude works from this list (so the owner does not need the chat history)\n")
w("1. Read `CLAUDE.md` (§3, §4.2b, §5) and **only this file** — no earlier conversation is needed.")
w("2. Take the **first 10 unchecked** clades under “Next batch” (or the number the owner names). "
  "Skip none; a parent comes before its children.")
w("3. For each: write `entries/tree/clades/<id>.yaml` as in §4.2b (sources from "
  "`data/raw/tree/clade_sources_*.json` / `clade_refs_*.json`; if the clade is not there, "
  "fetch its fixed Wikipedia revision and PBDB record). Never invent facts; doubts go to `curation.notes`.")
w("4. Place genera and fix the structure of the group from recent cladograms before writing its children "
  "(§4.8; record changes in `docs/TREE_REVIEW.md`). Informal groupings get no entry.")
w("5. `python3 scripts/fmt.py && python3 scripts/build.py && python3 scripts/validate.py` → 0 errors; "
  "look at the screenshots of one new entry.")
w("6. `python3 scripts/queue.py` (ticks the finished items), one commit per batch on a branch "
  "`entry/queue-<first-id>`, report to the owner. Never mark `checked`.\n")
w(f"**Progress: {n_done} / {total} backbone clades have an entry** "
  f"({total - n_done} to do). Clade entries inside volumes (Pterosauria, Pseudosuchia) are "
  f"counted in their own volumes, not here.\n")
w("## Next batch\n")
for r, d in todo[:10]:
    w(f"- [ ] `{r[0]}` — {r[1]} ({tips(r[0])} genera in the tree)")
if not todo:
    w("_Queue finished._")
w("\n## Full queue (depth-first, parents before children)\n")
w("Indentation = depth in the tree. `e` = extinct group, `v` = has living members.\n")
for r, d in order:
    mark = "x" if r[0] in done else " "
    fl = {"e": "e", "v": "v"}.get(r[3], "·")
    w(f"{'  ' * min(d, 12)}- [{mark}] `{r[0]}` — {r[1]} · {fl} · {tips(r[0])} gen.")
open(f"{ROOT}/docs/QUEUE.md", "w").write("\n".join(out) + "\n")
print(f"{n_done}/{total} done; next: {todo[0][0][0] if todo else '-'}")
