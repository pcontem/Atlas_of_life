#!/usr/bin/env python3
"""Regenerate docs/QUEUE.md: the ordered work list of clade entries still to be written.

Done = an entry file exists in entries/*/clades/<id>.yaml. Order = depth-first walk of
data/tree/backbone.json (parents before children), except that the subtrees listed in
docs/queue_priority.txt (one node id per line, '#' = comment) come first, in that order.
Run it after every batch:  python3 scripts/queue.py
"""
import json, glob, os, re, collections, sys

CLADE_MAX = int(os.environ.get("CLADE_MAX", 12))  # ...and at most this many sub-clades (keeps very inclusive clades with few known genera general)
UNIT_MAX = int(os.environ.get("UNIT_MAX", 30))  # a clade with at most this many genera is a production unit

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = json.load(open(f"{ROOT}/data/tree/backbone.json"))
by = {r[0]: r for r in rows}
kids = collections.defaultdict(list)
for r in rows:
    kids[r[2]].append(r)
done = {os.path.basename(f)[:-5] for f in glob.glob(f"{ROOT}/entries/*/clades/*.yaml")}
gdone = {os.path.basename(f)[:-5] for f in glob.glob(f"{ROOT}/entries/*/genera/*.yaml")}

def tips(i):
    return sum(1 if c[5] == "g" else tips(c[0]) for c in kids[i])

prio = []
p = f"{ROOT}/docs/queue_priority.txt"
if os.path.exists(p):
    prio = [l.split("#")[0].strip() for l in open(p) if l.split("#")[0].strip()]
    bad = [x for x in prio if x not in by]
    if bad:
        sys.exit(f"queue_priority.txt: unknown node ids: {bad}")


def genera_under(i):
    out = []
    for c in kids[i]:
        out += [c] if c[5] == "g" else genera_under(c[0])
    return out

def clades_under(i):
    out = []
    for c in kids[i]:
        if c[5] == "c":
            out.append(c)
            out += clades_under(c[0])
    return out

# Partition: the most inclusive clades with 1..UNIT_MAX genera are production units; everything above is a general clade.
general, units, direct = [], [], []
def walk(i, depth):
    r = by[i]
    n = tips(i)
    if 0 < n <= UNIT_MAX and len(clades_under(i)) <= CLADE_MAX:
        units.append((r, depth)); return
    general.append((r, depth))
    g = [c for c in kids[i] if c[5] == "g"]
    if g:
        direct.append((r, depth, g))
    for c in kids[i]:
        if c[5] == "c":
            walk(c[0], depth + 1)
for i in prio:
    walk(i, 0)
walk("vida", 0)
seen_ids = set()
def dedupe(lst):
    out = []
    for x in lst:
        if x[0][0] not in seen_ids:
            seen_ids.add(x[0][0]); out.append(x)
    return out
general, units, direct = dedupe(general), dedupe(units), dedupe(direct) if False else direct

# Production units: (title, clade row, clade rows to write, genus rows)
prod = []
for r, d in units:
    prod.append((r[1], r, [r] + clades_under(r[0]), genera_under(r[0])))
for r, d, g in direct:                       # genera sitting directly in a general clade
    for k in range(0, len(g), UNIT_MAX):
        part = g[k:k + UNIT_MAX]
        label = f"{r[1]} — direct genera" + (f" ({k // UNIT_MAX + 1})" if len(g) > UNIT_MAX else "")
        prod.append((label, r, [], part))
# Genera waiting inside a volume (their parent clade already has an entry in entries/<volume>/clades, not in the backbone)
vol_of = {os.path.basename(f)[:-5]: f.split("/")[-3] for f in glob.glob(f"{ROOT}/entries/*/clades/*.yaml")}
vol_wait = collections.defaultdict(list)
for r in rows:
    if r[5] == "g" and r[2] and r[2] not in by:
        vol_wait[r[2]].append(r)
vol_units = []
for pid, g in sorted(vol_wait.items()):
    for k in range(0, len(g), UNIT_MAX):
        part = g[k:k + UNIT_MAX]
        vol_units.append((f"{vol_of.get(pid, '?')} volume: {pid}" + (f" ({k // UNIT_MAX + 1})" if len(g) > UNIT_MAX else ""), [pid, pid], [], part))
order_ix = {r[0]: n for n, (r, _) in enumerate(general + units)}
prod.sort(key=lambda u: order_ix.get(u[1][0], 10**6))
prod = vol_units + prod   # volumes first: their raw data and clade entries already exist

n_gen_total = sum(len(u[3]) for u in prod)
n_gen_done = sum(1 for u in prod for g in u[3] if g[1] in gdone)
todo_general = [(r, d) for r, d in general if r[0] not in done]
zero = [r for r, d in general if tips(r[0]) == 0]

out = []; w = out.append
w("# Clade work queue — general clades (entry only)\n")
w("Generated by `python3 scripts/queue.py` — **do not edit by hand**. Order: [`queue_priority.txt`](queue_priority.txt). "
  "Genus work is in [`QUEUE_GENERA.md`](QUEUE_GENERA.md).\n")
w("## How Claude works from this list\n")
w("1. Read `CLAUDE.md` (§3, §4.2b, §5) and **only this file**.")
w("2. Take the **first 10 unchecked** clades under “Next batch” (parents before children).")
w("3. Write `entries/tree/clades/<id>.yaml` (§4.2b); sources from `data/raw/tree/clade_sources_*.json` / `clade_refs_*.json`; never invent; doubts go to `curation.notes`.")
w("4. fmt / build / validate → 0 errors; `python3 scripts/queue.py`; one commit per batch on `entry/queue-<first-id>`; never mark `checked`.")
w(f"5. A clade marked **→ unit** is NOT done here: it is a production unit (see QUEUE_GENERA.md), written together with its genera.\n")
w(f"**General clades: {sum(1 for r,_ in general if r[0] in done)} / {len(general)} have an entry.** "
  f"Production units hold the other {len(units)} clades' subtrees (threshold: {UNIT_MAX} genera per unit; set `UNIT_MAX` to change).\n")
w("## Next batch\n")
for r, d in todo_general[:10]:
    w(f"- [ ] `{r[0]}` — {r[1]} ({tips(r[0])} genera in the tree)")
if not todo_general:
    w("_All general clades have an entry._")
w("\n## Full list (depth-first, parents before children)\n")
w("`e` extinct, `v` living members. Units are pointers, not tasks here.\n")
unit_ids = {r[0] for r, _ in units}
gl = {r[0] for r, _ in general}
def emit(i, depth):
    r = by[i]
    if r[0] in unit_ids:
        w(f"{'  ' * min(depth, 12)}- → unit `{r[0]}` — {r[1]} · {tips(r[0])} gen."); return
    mark = "x" if r[0] in done else " "
    fl = {"e": "e", "v": "v"}.get(r[3], "·")
    note = " · placeholder (0 genera)" if tips(r[0]) == 0 else ""
    w(f"{'  ' * min(depth, 12)}- [{mark}] `{r[0]}` — {r[1]} · {fl} · {tips(r[0])} gen.{note}")
    for c in kids[i]:
        if c[5] == "c":
            emit(c[0], depth + 1)
for i in (prio or []):
    emit(i, 0)
if "vida" not in prio:
    emit("vida", 0)
open(f"{ROOT}/docs/QUEUE.md", "w").write("\n".join(out) + "\n")

# ---------------- production queue ----------------
out = []; w = out.append
w("# Production queue — clades with all their genera\n")
w("Generated by `python3 scripts/queue.py` — **do not edit by hand**. A *unit* is a less inclusive clade (at most "
  f"{UNIT_MAX} genera) or a block of genera sitting directly in a general clade. One unit = one conversation = one branch/PR.\n")
w("## How Claude works from this list\n")
w("1. Read `CLAUDE.md` and the `atlas-entries` skill (§0–§3 for genera, §4 for clades); take the **first unit** with unchecked items.")
w("2. Write the clade entries of the unit (parents first), then its genera in one batch (skill §3); the unit is finished when all boxes are ticked.")
w("3. Genera already having an entry in any volume are ticked automatically; do not redo them.")
w("4. `python3 scripts/queue.py`, commit, PR; never mark `checked`.\n")
w(f"**Progress: {n_gen_done} / {n_gen_total} genera have an entry** in {len(prod)} units "
  f"({sum(1 for u in prod if u[3] and all(g[1] in gdone for g in u[3]) and all(c[0] in done for c in u[2]))} complete).\n")
w("## Next units\n")
def complete(u):
    return all(g[1] in gdone for g in u[3]) and all(c[0] in done for c in u[2])
pending = [u for u in prod if not complete(u)]
for t, r, cl, g in pending[:10]:
    w(f"- `{r[0]}` — {t} · {len(g)} genera · {sum(1 for c in cl if c[0] not in done)} clade entries to write")
w("\n## All units\n")
for t, r, cl, g in prod:
    gd = sum(1 for x in g if x[1] in gdone); cd = sum(1 for c in cl if c[0] in done)
    w(f"### {'[x]' if complete((t,r,cl,g)) else '[ ]'} {t} (`{r[0]}`) — genera {gd}/{len(g)}, clades {cd}/{len(cl)}")
    if cl:
        w("Clades: " + ", ".join(f"{'~~' if c[0] in done else ''}`{c[0]}`{'~~' if c[0] in done else ''}" for c in cl))
    w("Genera: " + ", ".join(f"{'~~'+x[1]+'~~' if x[1] in gdone else x[1]}" for x in g) + "\n")
open(f"{ROOT}/docs/QUEUE_GENERA.md", "w").write("\n".join(out) + "\n")
print(f"general clades {sum(1 for r,_ in general if r[0] in done)}/{len(general)}; units {len(prod)}; genera {n_gen_done}/{n_gen_total}")
